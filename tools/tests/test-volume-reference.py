    def test_lima_template_paths_cannot_redirect_owned_fixture_or_image(self):
        for token in ("{{.User}}", "{{.Home}}", "literal}}"):
            for flags in (("--owned-fixture",), ("--owned-fixture", "--same-path-fixture")):
                root = self.base / token
