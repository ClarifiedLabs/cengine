    def crash(self):
        status = self.provision("--timeout", "10")
        with self.open() as run:
            run.destructive("crash", status["run_id"])
        return status

    def test_restart_exact_stopped_instance_and_same_daemon_durable_intent(self):
        status = self.crash()
        old = self.receipt()
        self.assertTrue(old["crash_verified"])
        self.assertEqual(old["lifecycle"][-1]["status"], "Stopped")
        def inspect(operation, root, vm):
            if operation == "start":
                durable = self.receipt()
                self.assertEqual(durable["phase"], "restarting")
                self.assertEqual(durable["lifecycle"][-1]["daemon_id"], old["daemon_id"])
                self.assertEqual(durable["restart_count"], 1)
                self.assertFalse(durable["crash_verified"])
        self.fake.before = inspect
        with self.open() as run:
            self.assertEqual(run.restart(status["run_id"])["phase"], "ready")
        new = self.receipt()
        self.assertEqual(old["daemon_id"], new["daemon_id"])
        self.assertEqual(old["globals"], new["globals"])
        socket_key = f'lima/{status["name"]}/sock/docker.sock'
        self.assertNotEqual(old["records"][socket_key]["ino"], new["records"][socket_key]["ino"])
        for path, record in old["records"].items():
            if path != socket_key:
                self.assertEqual(record, new["records"][path])
        self.assertEqual([event["phase"] for event in new["lifecycle"]],
                         ["crashing", "crashed", "restarting", "restart-unverified", "ready"])
        self.assertTrue(all(0 < kw["timeout"] <= 10 for _, kw in self.fake.calls))
        with self.open() as run:
            self.assertEqual(run.destructive("destroy", status["run_id"])["phase"], "destroyed")

