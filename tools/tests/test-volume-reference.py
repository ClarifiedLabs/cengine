# Exact Lima 2.2.0-generated default (not a network authorization).
DEFAULT_NETWORKS = b'''# Path to socket_vmnet executable. Because socket_vmnet is invoked via sudo it should be
# installed where only root can modify/replace it. This means also none of the
# parent directories can be writable by the user.
#
# The varRun directory also must not be writable by the user because it will
# include the socket_vmnet pid file. Those will be terminated via sudo, so replacing
# the pid file would allow killing of arbitrary privileged processes. varRun
# however MUST be writable by the daemon user.
#
# None of the paths segments may be symlinks, why it has to be /private/var
# instead of /var etc.
paths:
# socketVMNet requires Lima >= 0.12 .
  socketVMNet: "/opt/socket_vmnet/bin/socket_vmnet"
  varRun: /private/var/run/lima
  sudoers: /private/etc/sudoers.d/lima

# The group that is allowed to run socket_vmnet via sudo and to access the
# socket_vmnet socket (macOS only; ignored on other platforms). Non-admin users
# must set this to a group they belong to (e.g. "staff").
group: admin

networks:
  user-v2:
    mode: user-v2
    gateway: 192.168.104.1
    netmask: 255.255.255.0
  shared:
    mode: shared
    gateway: 192.168.105.1
    dhcpEnd: 192.168.105.254
    netmask: 255.255.255.0
  bridged:
    mode: bridged
    interface: en0
    # bridged mode doesn't have a gateway; dhcp is managed by outside network
  host:
    mode: host
    gateway: 192.168.106.1
    dhcpEnd: 192.168.106.254
    netmask: 255.255.255.0
'''


class FakeSubprocess:
    def __init__(self):
        self.calls = []
        self.sockets = []
        self.fail: str | None = None
        self.daemon_id = "reference-daemon-unique-id"
        self.engine_version = "29.2.1"
        self.lima_version = ref.LIMA_VERSION
        self.before: Callable | None = None
        self.vm_status = "Stopped"
        self.list_output: str | None = None
        self.stop_keeps_running = False
        self.retain_socket = False

    def __call__(self, argv, **kwargs):
        self.calls.append((argv, kwargs))
        root = Path(kwargs["cwd"])
        state = json.loads((root / "state.json").read_text())
        vm = root / "lima" / state["name"]
        operation = argv[1]
        if self.before:
            self.before(operation, root, vm)
        if operation == "--version":
            output = "limactl version " + self.lima_version + "\n"
        elif operation == "create":
            vm.mkdir(mode=0o700)
            # Lima is allowed to serialize JSON input to YAML; the actual stored
            # config is separately pinned after successful create, before start.
            (vm / "lima.yaml").write_text("# generated by fake Lima\n" + (root / "config.yaml").read_text())
            config = root / "lima" / "_config"
            config.mkdir(mode=0o700)
            (config / "user").write_text("private-key-fixture")
            (config / "user.pub").write_text("public-key-fixture")
            output = ""
        elif operation == "start":
            networks = root / "lima" / "_config" / "networks.yaml"
            if not networks.exists():
                networks.write_bytes(DEFAULT_NETWORKS)
            (vm / "sock").mkdir(mode=0o700, exist_ok=True)
            (vm / "sock" / "docker.sock").unlink(missing_ok=True)
            connection = socket.socket(socket.AF_UNIX)
            connection.bind(str(vm / "sock" / "docker.sock"))
            self.sockets.append(connection)
            self.vm_status = "Running"
            output = ""
        elif operation == "list":
            assert argv == [state["limactl"], "list", state["name"], "--json"]
            output = self.list_output if self.list_output is not None else json.dumps({
                "name": state["name"], "dir": str(vm), "vmType": "vz", "arch": "aarch64", "status": self.vm_status}) + "\n"
        elif operation == "--config":
            assert argv[3:7] == ["--host", state["endpoint"], "info", "--format"]
            output = json.dumps({"ID": self.daemon_id, "ServerVersion": self.engine_version,
                                 "OSType": "linux", "Architecture": "aarch64", "SecurityOptions": []})
        elif operation == "stop":
            assert argv == [state["limactl"], "stop", "--force", state["name"]]
            if not self.retain_socket:
                (vm / "sock" / "docker.sock").unlink()
            if not self.stop_keeps_running:
                self.vm_status = "Stopped"
            output = ""
        elif operation == "delete":
            assert argv == [state["limactl"], "delete", "--force", state["name"]]
            shutil.rmtree(vm)
            output = ""
        else:
            raise AssertionError("unexpected subprocess: " + repr(argv))
        kwargs["stdout"].write(output.encode())
        kwargs["stdout"].flush()
        if operation == self.fail:
            raise subprocess.TimeoutExpired(argv, kwargs["timeout"])
        return SimpleNamespace(returncode=0)

    def close(self):
        for connection in self.sockets:
            connection.close()


class ReferenceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="vr-", dir="/tmp")
        self.base = Path(self.temp.name).resolve()
        self.root = self.base / "run"
        self.image = self.base / "image.raw"
        self.image.write_bytes(b"pinned preinstalled cloud image fixture")
        # Keep fake inputs in trusted ancestry even when the checkout volume is
        # shared/writable. This does NOT qualify that checkout for real provisioning.
        fixture = self.base / "fixture-source.txt"
        fixture.write_bytes(ref.FIXTURE_SOURCE.read_bytes())
        self.enterContext(patch.object(ref, "FIXTURE_SOURCE", fixture))
        for name in ("limactl", "docker"):
            path = self.base / name
            path.write_text("#!/bin/sh\nexit 97\n")
            path.chmod(0o700)
        self.fake = FakeSubprocess()
        self.addCleanup(self.temp.cleanup)
        self.addCleanup(self.fake.close)
        for name, value in (("system", "Darwin"), ("machine", "arm64"), ("mac_ver", ("26.0", (), ""))):
            self.enterContext(patch.object(ref.platform, name, return_value=value))
        self.enterContext(patch.object(ref.os, "statvfs", return_value=SimpleNamespace(f_bavail=1000 * 1024**3, f_frsize=1)))
        self.enterContext(patch.dict(os.environ, {"DOCKER_CONTEXT": "foreign", "DOCKER_HOST": "unix:///foreign.sock",
                          "LIMA_HOME": str(self.base / "foreign-lima"), "COLIMA_HOME": str(self.base / "foreign-colima"),
                          "SSH_AUTH_SOCK": "/foreign-agent.sock", "HTTP_PROXY": "http://foreign.invalid"}))

    def args(self, *extra):
        return ref.parser().parse_args(["provision", "--allow-disposable-vm", "--root", str(self.root),
            "--image", str(self.image), "--image-sha256", ref.digest(self.image),
            "--engine-version", "29.2.1", "--limactl", str(self.base / "limactl"),
            "--docker", str(self.base / "docker"), *extra])

    def provision(self, *extra):
        return ref.provision(self.args(*extra), self.fake)

    def receipt(self):
        return json.loads((self.root / "state.json").read_text())

    def open(self):
        return ref.Reference(self.root, self.fake)

    def assert_guarded(self, mutation):
        state = self.receipt()
        vm = self.root / "lima" / state["name"]
        mutation(state, vm)
        count = len(self.fake.calls)
        with self.assertRaises((ref.Refusal, OSError)):
            with self.open() as run:
                run.destructive("destroy", state["run_id"])
        self.assertEqual(len(self.fake.calls), count)

    def test_provision_crash_exact_teardown_and_artifacts(self):
        status = self.provision()
        self.assertEqual(status["phase"], "ready")
        self.assertEqual(status["daemon_id"], self.fake.daemon_id)
        state = self.receipt()
        self.assertEqual(state["records"]["."]["ino"], self.root.stat().st_ino)
        self.assertEqual(state["records"]["config.yaml"]["sha256"], ref.digest(self.root / "config.yaml"))
        vm = self.root / "lima" / status["name"]
        self.assertIn("sha256", state["records"][str((vm / "lima.yaml").relative_to(self.root))])
        with self.open() as run:
            self.assertEqual(run.destructive("crash", status["run_id"])["phase"], "crashed")
        with self.open() as run:
            self.assertEqual(run.destructive("destroy", status["run_id"])["phase"], "destroyed")
        count = len(self.fake.calls)
        with self.open() as run:
            self.assertEqual(run.destructive("destroy", status["run_id"])["phase"], "destroyed")
        self.assertEqual(len(self.fake.calls), count)
        self.assertFalse(vm.exists())
        self.assertTrue((self.root / "artifacts").is_dir())
        self.assertTrue((self.root / "config.yaml").is_file())
        self.assertTrue((self.root / "state.json").is_file())
        for argv, kw in self.fake.calls:
            self.assertIsInstance(argv, list)
            self.assertLessEqual(kw["timeout"], 900)
            self.assertGreater(kw["timeout"], 0)
            self.assertEqual(kw["env"]["LIMA_HOME"], str(self.root / "lima"))
            self.assertEqual(kw["env"]["HOME"], str(self.root / "host-home"))
            for name in ("DOCKER_CONTEXT", "DOCKER_HOST", "SSH_AUTH_SOCK", "HTTP_PROXY"):
                self.assertNotIn(name, kw["env"])
            self.assertNotIn("shell", kw)
            self.assertEqual(kw["stdin"], subprocess.DEVNULL)

